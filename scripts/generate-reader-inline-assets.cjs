// Regenerates src/generated/readerInlineAssets.ts from assets/reader/*.
// Run: node scripts/generate-reader-inline-assets.cjs
// CI also runs this before bundling so inline assets never drift.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const READER = path.join(ROOT, 'assets', 'reader');
const OUT = path.join(ROOT, 'src', 'generated', 'readerInlineAssets.ts');

const JS_FILES = [
  'polyfill-onscrollend.js',
  'icons.js',
  'van.js',
  'text-vibe.js',
  'core.js',
  'search.js',
  'index.js',
  'textRemover.js',
];
const CSS_FILES = ['index.css', 'pageReader.css', 'toolWrapper.css', 'tts.css'];

const esc = s => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const parts = [
  '// AUTO-GENERATED by scripts/generate-reader-inline-assets.cjs. Do not edit manually.',
  '// Inline reader assets so WKWebView never needs file:// access (online chapters',
  '// load from http(s) baseUrl where file:// subresources are blocked).',
  '',
];
for (const f of JS_FILES) {
  const content = fs.readFileSync(path.join(READER, 'js', f), 'utf8');
  const varName = 'READER_JS_' + f.replace('.js', '').replace(/-/g, '_').toUpperCase();
  parts.push(`export const ${varName} = \`${esc(content)}\`;`);
}
for (const f of CSS_FILES) {
  const content = fs.readFileSync(path.join(READER, 'css', f), 'utf8');
  const varName = 'READER_CSS_' + f.replace('.css', '').replace(/-/g, '_').toUpperCase();
  parts.push(`export const ${varName} = \`${esc(content)}\`;`);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, parts.join('\n') + '\n');
console.log(`Wrote ${OUT} (${JS_FILES.length} js + ${CSS_FILES.length} css)`);
